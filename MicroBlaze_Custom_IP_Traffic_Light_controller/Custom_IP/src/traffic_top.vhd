--------------------------------------------------------------------
-- File        : traffic_top.vhd
-- Component   : traffic_top
-- Description :
--   This is the top-level VHDL component for the traffic-light system.
--
--   This component does not implement new control logic by itself.
--   Instead, it connects three internal components together:
--
--      1. TIMER_1S  - generates done_1s after 1 second
--      2. TIMER_2S  - generates done_2s after 2 seconds
--      3. FSM_U     - the traffic-light finite state machine
--
--   The FSM controls which timer is active:
--      en_1s is connected to TIMER_1S
--      en_2s is connected to TIMER_2S
--
--   The timers notify the FSM when the required delay is finished:
--      done_1s goes back to the FSM
--      done_2s goes back to the FSM
--
--   The switches_in input will come from AXI register 2
--   inside the custom IP.
--
--   The state_out output will be connected to AXI register 0.
--   The leds_out output will be connected to AXI register 1
--   and also to the external LED output port.
--

--------------------------------------------------------------------

library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;

entity traffic_top is
    generic(
        -- Basys 3 board clock is 100 MHz.
        CLK_FREQ_HZ : positive := 100_000_000
    );
    port(
        clk,rst: in  std_logic;
        
        switches_in : in  std_logic_vector(15 downto 0);

        -- Current FSM state.
        state_out   : out std_logic_vector(2 downto 0);

       
        leds_out: out std_logic_vector(15 downto 0)
    );
end traffic_top;

architecture Structural of traffic_top is

    -- Timer done signals
    signal done_1s : std_logic;
    signal done_2s : std_logic;

    -- Timer enable signals generated by the FSM
    signal en_1s   : std_logic;
    signal en_2s   : std_logic;

begin


    TIMER_1S : entity work.timer(Behavioral)
        generic map(
            SECONDS     => 1,
            CLK_FREQ_HZ => CLK_FREQ_HZ
        )
        port map(
            clk    => clk,
            enable => en_1s,
            done   => done_1s
        );

    TIMER_2S : entity work.timer(Behavioral)
        generic map(
            SECONDS     => 2,
            CLK_FREQ_HZ => CLK_FREQ_HZ
        )
        port map(
            clk    => clk,
            enable => en_2s,
            done   => done_2s
        );

 
    FSM_U : entity work.traffic_fsm(Behavioral)
        port map(
            clk         => clk,
            rst=>rst,
            switches_in => switches_in,

            done_1s     => done_1s,
            done_2s     => done_2s,

            en_1s       => en_1s,
            en_2s       => en_2s,

            state_out   => state_out,
            leds_out    => leds_out
        );

end Structural;